/**
 * Returns an inline SVG icon from the TRAVIAN_ICONS map.
 */
function makeSvgIcon(iconKey) {
  const icon = TRAVIAN_ICONS[iconKey];
  if (!icon) return "";
  return `<svg class="travian-icon" viewBox="${icon.viewBox}" xmlns="http://www.w3.org/2000/svg"><path d="${icon.path}"/></svg>`;
}

/**
 * Returns a Travian native CSS sprite icon (used for resources r1-r4).
 * These rely on Travian's own stylesheets already loaded on the page.
 */
function makeNativeIcon(cssClass) {
  return `<i class="${cssClass} travian-native-icon"></i>`;
}

/**
 * Detects alarm type from its name and returns the appropriate inline SVG icon HTML.
 * @param {string} name - The raw alarm name
 * @returns {string} HTML string with an <svg> element, or empty string
 */
function getAlarmSvgIcon(name) {
  if (!name) return "";
  const lower = name.toLowerCase();

  // 1. Attack sirens
  if (name.includes("🚨")) return makeSvgIcon("Siren");

  // 2. Attack trackers
  if (name.includes("⚠️")) return makeSvgIcon("Alert");

  // 3. Hero (⚔️)
  if (name.includes("⚔️")) return makeSvgIcon("Swords");

  // 4. Farm List / Daily — emoji shown as-is, no SVG override
  if (name.includes("🚜")) return "";
  if (name.includes("📅")) return "";

  // 5. Custom alarms (⭐)
  if (name.includes("⭐")) return makeSvgIcon("Star");

  // 5. Training alarms (🎓 Troop Queue - BuildingName)
  if (name.includes("🎓")) {
    const match = name.match(/Troop Queue\s*-\s*([^(]+)/i);
    if (match) {
      const buildingName = match[1].trim().toLowerCase();
      const key = BUILDING_ICON_MAP[buildingName];
      if (key) return resolveIconKey(key);
    }
    return makeSvgIcon("Barracks");
  }

  // 6. Celebrations (🎉)
  if (name.includes("🎉")) return makeSvgIcon("Celebration");

  // 7. Storage alarms (📦) - warehouse/granary fill with resource icons
  if (name.includes("📦")) {
    if (lower.includes("granary") || lower.includes("crop"))
      return makeNativeIcon("r4");
    if (lower.includes("warehouse")) return makeNativeIcon("r0");
    if (lower.includes("wood")) return makeNativeIcon("r1");
    if (lower.includes("clay")) return makeNativeIcon("r2");
    if (lower.includes("iron")) return makeNativeIcon("r3");
    return makeSvgIcon("Warehouse");
  }

  // 8. Resource alarms - use Travian's native CSS sprite icons
  if (name.includes("🌾")) return makeNativeIcon("r4"); // r4 = crop
  if (name.includes("🪵")) return makeNativeIcon("r1"); // r1 = lumber/wood
  if (name.includes("🧱")) return makeNativeIcon("r2"); // r2 = clay
  if (name.includes("🔩")) return makeNativeIcon("r3"); // r3 = iron

  return "";
}

/**
 * Resolves an icon key - if it starts with '_' it's a native CSS class, otherwise SVG.
 */
function resolveIconKey(key) {
  if (key.startsWith("_")) return makeNativeIcon(key.substring(1));
  return makeSvgIcon(key);
}

